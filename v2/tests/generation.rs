use tezbar_markdown_table_generator::{generate, output_size, Error, MAX_OUTPUT_BYTES};

#[test]
fn known_literal_and_trailing_lf() {
    assert_eq!(generate("2", "2").unwrap(), "| Column 1 | Column 2 |\n| --- | --- |\n| Cell 1-1 | Cell 1-2 |\n| Cell 2-1 | Cell 2-2 |\n");
}

#[test]
fn exact_limit_and_first_rejected_row() {
    // Independent fixed regression fixture, exactly 8 MiB (4,124 x 136).
    let table = generate("4124", "136").unwrap();
    assert_eq!(table.len() as u64, MAX_OUTPUT_BYTES);
    assert!(table.ends_with(" Cell 4124-136 |\n"));
    assert_eq!(output_size(4124, 136), Ok(MAX_OUTPUT_BYTES));
    assert_eq!(generate("4125", "136"), Err(Error::OutputTooLarge));
}

#[test]
fn asymmetric_limits_and_checked_overflow() {
    for (rows, columns, expected) in [(472205, 1, 8388606), (1, 226600, 8388596)] {
        // Check literals below against generated byte lengths, not another formula.
        let table = generate(&rows.to_string(), &columns.to_string()).unwrap();
        assert_eq!(table.len() as u64, expected);
        assert_eq!(output_size(rows, columns), Ok(expected));
    }
    for (rows, columns) in [
        (u64::MAX, 1),
        (1, u64::MAX),
        (u64::MAX, u64::MAX),
        (1 << 32, 1 << 32),
    ] {
        assert_eq!(output_size(rows, columns), Err(Error::OutputTooLarge));
    }
    assert_eq!(generate("472206", "1"), Err(Error::OutputTooLarge));
    assert_eq!(generate("1", "226601"), Err(Error::OutputTooLarge));
    assert_eq!(
        generate("18446744073709551615", "1"),
        Err(Error::OutputTooLarge)
    );
    assert_eq!(generate("1", &"9".repeat(308)), Err(Error::OutputTooLarge));
    assert_eq!(
        generate(&"9".repeat(309), "1"),
        Err(Error::InvalidArguments)
    );
    assert_eq!(
        generate(&"9".repeat(308), "bad"),
        Err(Error::InvalidArguments)
    );
}
